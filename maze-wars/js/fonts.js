  function build(src, spacing, spaceW) {
    const g = {};
    for (const ch in src) {
      const rows = src[ch][1].split('/');
      let w = 0; for (const r of rows) if (r.length > w) w = r.length;
      const bits = rows.map(r => { const a = new Uint8Array(w); for (let i = 0; i < r.length; i++) a[i] = r[i] === '#' ? 1 : 0; return a; });
      g[ch] = { top: src[ch][0], w, rows: bits };
    }
    g[' '].w = spaceW;
    return { g, sp: spacing, cap: 9 };
  }
  MW.FONT = { chi: build(CHI, 2, 4), gen: build(GEN, 2, 3) };
  // Anything we cannot draw becomes '?', so text from the network can never break layout.
  MW.FONT.clean = function (s, max) {
    let out = ''; s = String(s == null ? '' : s).replace(/’/g, "'").replace(/[“”]/g, '"').replace(/—|–/g, '-');
    for (const ch of s) { if (out.length >= max) break; out += (CHI[ch] && GEN[ch] && ch !== '') ? ch : (ch === '\n' || ch === '\t' ? ' ' : '?'); }
    return out;
  };
